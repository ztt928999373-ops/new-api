#!/usr/bin/env bash

diff_result=
compare_files() {
  local left=$1 right=$2 output=$3 rc
  if diff -u "$left" "$right" >"$output"; then
    diff_result=UNCHANGED
    return 0
  else
    rc=$?
  fi
  if (( rc == 1 )); then
    diff_result=CHANGED
    return 0
  fi
  diff_result=ERROR
  return "$rc"
}

validate_daemon_network_settings() {
  jq -e '
    type == "object" and
    all(["iptables", "ip6tables", "allow-direct-routing"][];
      . as $key | (($cfg | has($key)) | not) or ($cfg[$key] | type == "boolean")
    ) and
    .iptables != false and
    .ip6tables != false and
    .["allow-direct-routing"] != true
  ' "$1" >/dev/null
}

candidate_origins() {
  local policy=$1 candidate=$2
  awk -v candidate="$candidate" '
    {
      line=$0; sub(/^[[:space:]]+/, "", line)
      if (line ~ /^\*\*\*/) { sub(/^\*\*\*[[:space:]]+/, "", line); split(line, fields, /[[:space:]]+/); in_candidate=(fields[1] == candidate); next }
      split(line, fields, /[[:space:]]+/)
      if (fields[2] ~ /^[0-9]+$/) { in_candidate=(fields[1] == candidate); next }
      if (in_candidate && line ~ /^[0-9]+[[:space:]]+https?:\/\//) print line
    }
  ' <<< "$policy"
}

normalize_firewall() {
  local family=$1 source=$2 destination=$3
  if [[ $family == nft ]]; then
    sed -E '/^# Generation ID:/d; s/counter packets [0-9]+ bytes [0-9]+/counter packets COUNTER bytes COUNTER/g; s/ handle [0-9]+//g' "$source" > "$destination"
  else
    sed -E '/^# Generated by .* on /d; /^# Completed on /d; s/\[[0-9]+:[0-9]+\]/[COUNTERS]/g' "$source" > "$destination"
  fi
}
