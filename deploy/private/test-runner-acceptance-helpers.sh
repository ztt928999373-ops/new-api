#!/usr/bin/env bash
set -Eeuo pipefail
here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
source "$here/runner-acceptance-helpers.sh"
tmp=$(mktemp -d)
trap 'rm -rf -- "$tmp"' EXIT

printf 'same\n' > "$tmp/left"
printf 'same\n' > "$tmp/right"
compare_files "$tmp/left" "$tmp/right" "$tmp/diff.out"
[[ $diff_result == UNCHANGED ]]

printf 'different\n' > "$tmp/right"
compare_files "$tmp/left" "$tmp/right" "$tmp/diff.out"
[[ $diff_result == CHANGED ]]
grep -q '^[-]same$' "$tmp/diff.out"

mkdir "$tmp/bin"
cat > "$tmp/bin/diff" <<'EOF'
#!/usr/bin/env bash
exit 2
EOF
chmod +x "$tmp/bin/diff"
if PATH="$tmp/bin:$PATH" compare_files "$tmp/left" "$tmp/right" "$tmp/diff.out"; then
  echo 'diff execution error was accepted' >&2
  exit 1
else
  [[ $diff_result == ERROR ]]
fi

if command -v jq >/dev/null 2>&1; then
  printf '{}\n' > "$tmp/settings.json"
  validate_daemon_network_settings "$tmp/settings.json"
  printf '{"iptables":true,"ip6tables":true,"allow-direct-routing":false}\n' > "$tmp/settings.json"
  validate_daemon_network_settings "$tmp/settings.json"
  for invalid in \
    '{"iptables":false}' \
    '{"ip6tables":false}' \
    '{"allow-direct-routing":true}' \
    '{"iptables":"false"}' \
    '{"ip6tables":null}' \
    '{"allow-direct-routing":0}'; do
    printf '%s\n' "$invalid" > "$tmp/settings.json"
    if validate_daemon_network_settings "$tmp/settings.json"; then
      echo "unsafe daemon settings were accepted: $invalid" >&2
      exit 1
    fi
  done
else
  [[ ${ALLOW_MISSING_JQ_TESTS:-0} == 1 ]] || { echo 'jq is required for daemon-settings test cases.' >&2; exit 1; }
  echo 'DOCKER_DAEMON_JQ_CASES=NOT_RUN (jq unavailable)'
fi

policy='docker-ce:
  Installed: (none)
  Candidate: 5:30.0.0-1~ubuntu.24.04~noble
  Version table:
     5:30.0.0-1~ubuntu.24.04~noble 500
        500 https://download.docker.com/linux/ubuntu noble/stable amd64 Packages
     5:29.0.0-1~ubuntu.24.04~noble 500
        500 https://archive.ubuntu.com/ubuntu noble-updates/universe amd64 Packages'
origins=$(candidate_origins "$policy" '5:30.0.0-1~ubuntu.24.04~noble')
[[ $origins == '500 https://download.docker.com/linux/ubuntu noble/stable amd64 Packages' ]]
printf '# Generation ID: 15\ntable inet filter { chain input { counter packets 1 bytes 64 accept comment "policy" } } # handle 11\n' > "$tmp/nft.before"
printf '# Generation ID: 99\ntable inet filter { chain input { counter packets 90 bytes 800 accept comment "policy" } } # handle 27\n' > "$tmp/nft.after"
normalize_firewall nft "$tmp/nft.before" "$tmp/nft.before.normalized"
normalize_firewall nft "$tmp/nft.after" "$tmp/nft.after.normalized"
compare_files "$tmp/nft.before.normalized" "$tmp/nft.after.normalized" "$tmp/firewall.diff"
[[ $diff_result == UNCHANGED ]]
printf '# Generated by iptables-save v1 on 2026-01-01\n-A INPUT -p tcp -m conntrack --ctstate NEW -j ACCEPT [1:64]\n# Completed on 2026-01-01\n' > "$tmp/iptables.before"
printf '# Generated by iptables-save v1 on 2026-01-02\n-A INPUT -p tcp -m conntrack --ctstate NEW -j ACCEPT [90:800]\n# Completed on 2026-01-02\n' > "$tmp/iptables.after"
normalize_firewall iptables-v4 "$tmp/iptables.before" "$tmp/iptables.before.normalized"
normalize_firewall iptables-v4 "$tmp/iptables.after" "$tmp/iptables.after.normalized"
compare_files "$tmp/iptables.before.normalized" "$tmp/iptables.after.normalized" "$tmp/firewall.diff"
[[ $diff_result == UNCHANGED ]]
echo 'RUNNER_ACCEPTANCE_HELPERS=PASS'
